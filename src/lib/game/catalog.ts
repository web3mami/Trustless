export function profileFaction(faction: GameFaction): Faction {
  return faction === "village" ? "good" : faction;
}

export function revealFor(role: RoleDefinition): RoleReveal {
  return {
    id: role.id,
    name: role.name,
    faction: role.faction,
    category: role.category,
    description: role.description,
    abilityDescription: role.abilityDescription,
    winCondition: role.winCondition,
    phase: role.phase,
    targetType: role.targetType,
    maxTargets: role.maxTargets,
    notes: role.notes,
  };
}

export function apparentFaction(role: RoleDefinition): GameFaction {
  return role.investigationResult ?? role.faction;
}
