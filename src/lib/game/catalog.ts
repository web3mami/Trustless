function role(
  definition: Omit<RoleDefinition, "actionScope" | "cooldown" | "enabled" | "blockable"> &
    Partial<Pick<RoleDefinition, "actionScope" | "cooldown" | "enabled" | "blockable">>,
): RoleDefinition {
  return {
    actionScope: "personal",
    cooldown: null,
    enabled: true,
    blockable: definition.actionType !== null && definition.phase !== "passive",
    ...definition,
  };
}

